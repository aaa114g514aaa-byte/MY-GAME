# ── 标题装饰 ──
SEP = "=" * 40

FOOTER = "\n{:^40s}\n".format("-- 第 {} 次点火 --")


def main():
    quote = random.choice(QUOTES)
    count = len(sys.argv) > 1 and sys.argv[1].isdigit() and int(sys.argv[1]) or 0

    print(f"\n{SEP}")
    print(f"    「{quote}」")
    print(FOOTER.format(count or random.randint(1, 9999)))


if __name__ == "__main__":
    main()
